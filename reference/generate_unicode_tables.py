"""Generate Nathr's pinned Unicode General_Category lookup ranges."""

import argparse
import hashlib
from pathlib import Path


def categories(path, digest):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError(f"{path}: Unicode data SHA-256 mismatch")
    groups = {"L": [], "N": []}
    first = None
    for line in data.decode("ascii").splitlines():
        code, name, category, *_ = line.split(";")
        point = int(code, 16)
        if name.endswith(", First>"):
            first = point
            continue
        if category[0] in groups:
            spans = groups[category[0]]
            begin = point if first is None else first
            if spans and spans[-1][1] + 1 == begin:
                spans[-1] = (spans[-1][0], point)
            else:
                spans.append((begin, point))
        first = None
    return groups


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("unicode16", type=Path)
    parser.add_argument("unicode17", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    u16 = categories(args.unicode16, "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f")
    u17 = categories(args.unicode17, "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c")
    lines = [
        "// Generated by reference/generate_unicode_tables.py. See LICENSE.unicode.",
        "#pragma once", "", "namespace nathr::detail {", "",
        "struct UnicodeRange { char32_t first, last; };", "",
    ]
    for name, spans in (("letters_16", u16["L"]), ("numbers_16", u16["N"]), ("numbers_17", u17["N"])):
        lines.append(f"inline constexpr UnicodeRange {name}[] = {{")
        lines.extend(f"    {{0x{first:X}, 0x{last:X}}}," for first, last in spans)
        lines.extend(["};", ""])
    lines.append("} // namespace nathr::detail")
    args.output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
