"""Extract encoding-defined lookup tables from the pinned MIT GGML source."""

import argparse
import hashlib
from pathlib import Path
import re


REVISION = "b1b770d90d94cad9e9ea5b993bdbc383a522fb28"
HEADER_SHA256 = "0061131b615c5721fc88a78feeb22c1f8c450f1c2646a317d80796a653bf595c"
TABLES = (
    ("iq2xxs_grid", "std::uint64_t", 256),
    ("iq2xs_grid", "std::uint64_t", 512),
    ("iq2s_grid", "std::uint64_t", 1024),
    ("iq3xxs_grid", "std::uint32_t", 256),
    ("iq3s_grid", "std::uint32_t", 512),
    ("iq1s_grid", "std::uint64_t", 2048),
    ("kvalues_iq4nl", "std::int8_t", 16),
)


def verify_independent(source, tables):
    from gguf import quants
    import numpy as np

    classes = (quants.IQ2_XXS, quants.IQ2_XS, quants.IQ2_S, quants.IQ3_XXS,
               quants.IQ3_S, quants.IQ1_S)
    for (name, words, values_per_word), cls in zip(tables, classes, strict=True):
        cls.init_grid()
        unpacked = np.array([
            [(word >> (8 * i)) & 255 for i in range(values_per_word)] for word in words
        ], dtype=np.uint8)
        if cls is quants.IQ1_S:
            unpacked = unpacked.view(np.int8)
        np.testing.assert_array_equal(unpacked, cls.grid.reshape(cls.grid_shape), err_msg=name)
    signs = re.search(r"ksigns_iq2xs,[^\n]+\)\s*(.*?)GGML_TABLE_END\(\)", source, re.DOTALL)
    table = [int(value) for value in signs[1].replace("\n", "").split(",") if value.strip()]
    if table != list(quants.IQ2_XXS.ksigns) or table != [i | ((i.bit_count() & 1) << 7) for i in range(128)]:
        raise ValueError("independent sign parity tables disagree")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ggml_common", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--verify-oracle", action="store_true")
    args = parser.parse_args()
    data = args.ggml_common.read_bytes()
    if hashlib.sha256(data).hexdigest() != HEADER_SHA256:
        raise ValueError("GGML codebook source hash differs from the frozen manifest")
    source = data.decode()
    lines = [
        "// Encoding data from GGML at " + REVISION + ".",
        "// Generated by reference/generate_iq_codebooks.py. See LICENSE.ggml.",
        "#pragma once", "", "#include <cstdint>", "", "namespace nathr::detail::codebooks {", "",
    ]
    grids = []
    for name, dtype, count in TABLES:
        pattern = rf"GGML_TABLE_BEGIN\([^,]+,\s*{name},[^\n]+\)\s*(.*?)GGML_TABLE_END\(\)"
        match = re.search(pattern, source, re.DOTALL)
        if not match:
            raise ValueError(f"missing GGML codebook {name}")
        entries = [value.strip() for value in match[1].split(",") if value.strip()]
        if len(entries) != count:
            raise ValueError(f"unexpected codebook length for {name}: {len(entries)}")
        if dtype != "std::int8_t":
            grids.append((name, [int(value, 0) for value in entries], 8 if dtype == "std::uint64_t" else 4))
        width = 16 if dtype == "std::int8_t" else 4 if dtype == "std::uint64_t" else 8
        suffix = "ULL" if dtype == "std::uint64_t" else "U" if dtype == "std::uint32_t" else ""
        lines.append(f"inline constexpr {dtype} {name}[{count}] = {{")
        for i in range(0, len(entries), width):
            lines.append("    " + ", ".join(entry + suffix for entry in entries[i:i+width]) + ",")
        lines.extend(["};", ""])
    if args.verify_oracle:
        from gguf.quants import IQ4_NL

        verify_independent(source, grids)
        if tuple(map(int, entries)) != IQ4_NL.kvalues:
            raise ValueError("IQ4_NL codebook differs from the independent oracle")
    lines.append("} // namespace nathr::detail::codebooks")
    args.output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
